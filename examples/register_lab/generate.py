"""Generate/check cookbook project artifacts using the public SVX CLI."""

from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    target = root / "examples/register_lab/generated/models.sv"
    command = [sys.executable, "-m", "svx", "svtypes-gen", "--module",
               "examples.register_lab.models", "--channel-helpers"]
    if args.check:
        result = subprocess.run(command, cwd=root, check=True, capture_output=True)
        if not target.exists() or target.read_bytes() != result.stdout:
            raise SystemExit("Register lab models are stale; rerun generate.py")
        print("REGISTER_LAB_MODELS_CURRENT")
    else:
        subprocess.run([*command, "--out", str(target)], cwd=root, check=True)

    output = "examples/register_lab/generated"
    discovery = [sys.executable, "-m", "svx", "inheritance-manifest",
                 "--python-module", "examples.register_lab.extensions",
                 "--sv-source", "examples/register_lab/register_if.sv",
                 "--sv-source", "examples/register_lab/policy_types.sv",
                 "--out", f"{output}/inheritance.json"]
    generation = [sys.executable, "-m", "svx", "inheritance-gen",
                  "--manifest", f"{output}/inheritance.json",
                  "--sv-source", "examples/register_lab/register_if.sv",
                  "--sv-source", "examples/register_lab/policy_types.sv",
                  "--python-out", f"{output}/python",
                  "--sv-out", f"{output}/inheritance.sv",
                  "--artifact-manifest", f"{output}/svx-artifacts.json"]
    for command in (discovery, generation):
        subprocess.run([*command, *(["--check"] if args.check else [])],
                       cwd=root, check=True)
    from examples.register_lab.reporting import ADAPTER

    report = ("// Generated by examples/register_lab/generate.py. Do not edit.\n"
              "package register_report_pkg;\n  import svx_pkg::*;\n" +
              ADAPTER.render_sv("Report") + "endpackage\n")
    report_path = root / output / "report.sv"
    if args.check:
        if not report_path.exists() or report_path.read_text() != report:
            raise SystemExit("Register lab report adapter is stale; rerun generate.py")
    elif not report_path.exists() or report_path.read_text() != report:
        report_path.write_text(report)
    print("REGISTER_LAB_ARTIFACTS_CURRENT" if args.check else "REGISTER_LAB_GENERATED")


if __name__ == "__main__":
    main()
