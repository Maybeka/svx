"""Native field-reference binding and same-scope generated operation kernels."""
import json
import re


def compact_field_bindings(source, header_name, native_aliases=None):
    """Emit one concrete-type template, with only instance binding parameters."""
    definitions, shapes = [], {}
    native_aliases = native_aliases or {}
    pattern = re.compile(
        r'    typedef (?P<declaration>[^\n]+);\n'
        r'    `SVX_FIELD_ACCESSORS\((?P<alias>\w+), (?P<getter>\w+), (?P<setter>\w+), this\.(?P<member>\w+)\)\n'
        r'    // Core field binding: (?P=member)\n'
        r'(?P<body>    function void (?P<function>\w+)\([^\n]*\);.*?    endfunction)', re.S)

    def replace(match):
        member, function = match.group('member', 'function')
        body = match.group('body')
        parameters, arguments = ['NAME', 'MEMBER'], [function, 'this.' + member]
        body = re.sub(r'\b' + re.escape(function) + r'\b', 'NAME', body)
        for group, replacement in (('getter', 'NAME``_read'), ('setter', 'NAME``_write')):
            body = re.sub(r'\b' + re.escape(match.group(group)) + r'\b', replacement, body)
        body = body.replace('this.' + member, 'this.MEMBER')
        body = body.replace('this.MEMBER', 'MEMBER')
        literals = re.findall(r'"(?:\\.|[^"\\])*"', body)
        identity = next((json.loads(value).split('@svx_field_')[0] for value in literals if '@svx_field_' in value), None)
        if identity:
            parameters.append('FIELD_ID')
            arguments.append(json.dumps(identity))
            for value in set(literals):
                decoded = json.loads(value)
                if decoded.startswith(identity):
                    suffix = decoded[len(identity):]
                    body = body.replace(value, '{FIELD_ID, ' + json.dumps(suffix) + '}' if suffix else 'FIELD_ID')
        declaration = re.sub(r'\b' + re.escape(match.group('alias')) + r'\b', 'NAME``_type', match.group('declaration'))
        body = ('    typedef ' + declaration + ';\n'
                '    `SVX_FIELD_ACCESSORS(NAME``_type, NAME``_read, NAME``_write, MEMBER)\n' + body)
        body = re.sub(r'\bSVX(?:Scoped)?Value_\w+\b',
                      lambda token: native_aliases.get(token[0], token[0]), body)
        body = '\n'.join(line[4:] if line.startswith('    ') else line
                         for line in body.splitlines() if not line.strip().startswith('//'))
        key = (tuple(parameters), body)
        if key not in shapes:
            type_name = re.sub(r'\bNAME``_type\b', '', declaration).strip()
            type_name = re.sub(r'\bSVX(?:Scoped)?Value_\w+\b',
                               lambda token: native_aliases.get(token[0], token[0]), type_name)
            readable_type = re.sub(r'[^A-Za-z0-9_]+', '_', type_name).strip('_')
            unit = header_name.removeprefix('support/').removesuffix('_fields.svh')
            prefix = unit.replace('_', '_u_').replace('/', '_p_').replace('.', '_d_').upper()
            name = '_SVX_' + prefix + '_FIELD_' + readable_type
            suffix = 2
            while name in shapes.values():
                name = '_SVX_' + prefix + '_FIELD_' + readable_type + '_' + str(suffix)
                suffix += 1
            shapes[key] = name
            definitions.append('`define ' + name + '(' + ', '.join(parameters) + ') \\\n' +
                               ' \\\n'.join(body.splitlines()) + '\n')
        return ('    `' + shapes[key] + '(\n'
                + ',\n'.join('      ' + argument for argument in arguments) + '\n    )')

    result = pattern.sub(replace, source)
    if not definitions:
        return source, None
    first, rest = result.split('\n', 1)
    cleanup = '\n' + '\n'.join('`undef ' + name for name in shapes.values()) + '\n'
    return (first + '\n`include "' + header_name + '"\n' + rest + cleanup,
            '// Generated by svx inheritance-gen.\n'
            '// Shared native field operation templates. Arguments retain the original member binding.\n' + '\n'.join(definitions))


def field_kernel(field, cases, core_name):
    from .sv_codegen_mode import use_type_reference
    parameters = 'input string method_id, ref byte unsigned bytes[$], output bit ok, output chandle response, output string error'
    labels = [json.JSONDecoder().raw_decode(line.strip())[0] for line in cases
              if line.startswith('        "') and line.endswith(': begin')]
    dispatch = ['        '+', '.join(json.dumps(label) for label in labels)+': begin',
                f'          this.{core_name}(method_id, bytes, ok, response, error);', '        end']
    from pyslang import SourceManager
    from .sv_scan import _pyslang, _check_source_diagnostics
    from .errors import SVXInheritanceError

    prefix = 'class SVXFieldScan; function void invoke(); case(method_id)\n'
    suffix = '\nendcase endfunction endclass\n'
    source = prefix+'\n'.join(cases)+suffix
    tree = _pyslang().SyntaxTree.fromText(source, SourceManager())
    _check_source_diagnostics(tree, 'generated field operation kernel')
    spans = []
    def visit(node):
        if type(node).__name__ != 'ScopedNameSyntax' or str(node.left).strip() != 'this':
            return
        member = node.right.getFirstToken()
        if member.valueText == field.name:
            spans.append((node.left.sourceRange.start.offset, member.range.end.offset))
        else:
            raise SVXInheritanceError(f'field kernel for {field.name} unexpectedly accesses owner member {member.valueText}')
    tree.root.visit(visit)
    if not use_type_reference():
        return ([f'    // Core field binding: {field.name}',
                 f'    function void {core_name}({parameters});',
                 '      response = null;', '      case (method_id)', *cases,
                 '        default: begin ok = 0; error = "unsupported field operation"; end',
                 '      endcase', '    endfunction', ''], dispatch)
    data = source.encode('utf-8')
    resident = '__svx_resident_value'
    for start, end in sorted(set(spans), reverse=True):
        data = data[:start]+resident.encode()+data[end:]
    rewritten = data.decode('utf-8')[len(prefix):-len(suffix)].splitlines()
    kernel = '__svx_field_kernel_'+core_name.removeprefix('_svx__core_field_')
    core = [f'    // Core field binding: {field.name}',
            f'    function void {core_name}({parameters});',
            f'      {kernel}#(type(this.{field.name}))::invoke(this.{field.name}, method_id, bytes, ok, response, error);',
            '    endfunction', '']
    support = [f'    class {kernel} #(type SVXResidentType = int);',
               f'      static function void invoke(ref SVXResidentType {resident}, {parameters});',
               '        response = null;', '        case (method_id)', *rewritten,
               '          default: begin ok = 0; error = "unsupported field operation"; end',
               '        endcase', '      endfunction', '    endclass', '']
    return [*support, *core], dispatch
