"""Keep member logic local, separating only pure contract data and codec records."""
import ast
import re
from pathlib import PurePosixPath


def split_python_support(sources):
    from .generated_names import readable
    result = dict(sources)
    for path, source in sources.items():
        if path.suffix != '.py' or not source.startswith('# Generated by svx inheritance-gen.'):
            continue
        tree = ast.parse(source)
        parents = {child: node for node in ast.walk(tree) for child in ast.iter_child_nodes(node)}
        def registration(call):
            scope = parents[call]
            while True:
                if isinstance(scope, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    imports = {alias.asname or alias.name: alias.name
                               for item in scope.body if isinstance(item, ast.ImportFrom)
                               and item.module == 'svx.inheritance'
                               for alias in item.names if alias.name in {'register_contract', 'register_constructor'}}
                    if call.func.id in imports:
                        return imports[call.func.id]
                    # Do not move a call through a locally shadowed function.
                    arguments = getattr(scope, 'args', None)
                    if arguments is not None and any(arg.arg == call.func.id for arg in
                            (*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs,
                             *((arguments.vararg,) if arguments.vararg else ()),
                             *((arguments.kwarg,) if arguments.kwarg else ()))):
                        return None
                    for item in scope.body:
                        if isinstance(item, (ast.Assign, ast.AnnAssign, ast.AugAssign)) and any(
                                isinstance(child, ast.Name) and child.id == call.func.id
                                and isinstance(child.ctx, ast.Store) for child in ast.walk(item)):
                            return None
                if scope is tree:
                    return None
                scope = parents[scope]
        occupied = {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}
        edits = []
        constants = []
        support_names = set()
        support_path = PurePosixPath('svx_support') / path
        support_module = '.'.join(support_path.parent.parts if support_path.name == '__init__.py'
                                  else support_path.with_suffix('').parts)
        # AST columns are UTF-8 byte offsets. Index the file once rather than
        # having get_source_segment split the entire file for every literal.
        data = source.encode('utf-8')
        offsets = [0, *(match.end() for match in re.finditer(rb'\r\n|\r|\n', data))]
        source_lines = re.split(r'\r\n|\r|\n', source)
        def source_segment(node):
            return data[offsets[node.lineno-1]+node.col_offset:
                        offsets[node.end_lineno-1]+node.end_col_offset].decode('utf-8')
        for node in sorted(ast.walk(tree), key=lambda node: getattr(node, 'lineno', 0)):
            if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)):
                continue
            call = node.value
            if not isinstance(call.func, ast.Name):
                continue
            api = registration(call)
            if api is None:
                continue
            if source_lines[node.lineno-1].encode('utf-8')[:node.col_offset].strip():
                continue  # Preserve inline suites and multiple statements.
            if source_lines[node.end_lineno-1].encode('utf-8')[node.end_col_offset:].strip():
                continue
            try:
                for value in (*call.args, *(keyword.value for keyword in call.keywords)):
                    ast.literal_eval(value)
            except (ValueError, TypeError):
                continue  # Never move lexical dependencies into another module.
            if any(keyword.arg is None for keyword in call.keywords):
                continue
            first = ast.literal_eval(call.args[0]) if call.args else api
            identity = next(iter(first), api) if isinstance(first, dict) else first
            label = readable('/'.join(str(identity).split('/')[-2:]))[:52]
            imports = []
            def operand(value, name):
                if isinstance(value, ast.Constant):
                    return source_segment(value)
                base = label + '_' + name
                symbol = base
                suffix = 2
                while symbol in support_names:
                    symbol = f'{base}_{suffix}'
                    suffix += 1
                support_names.add(symbol)
                alias = '_svx__' + symbol
                while alias in occupied:
                    alias += '_'
                occupied.add(alias)
                imports.append(f'{symbol} as {alias}')
                constants.extend([f'{symbol} = '+source_segment(value), ''])
                return alias
            names = ('contract',) if api == 'register_contract' else ('class_id', 'parameters')
            arguments = [operand(value, names[index] if index < len(names) else f'argument_{index+1}')
                         for index, value in enumerate(call.args)]
            arguments.extend(keyword.arg+'='+operand(keyword.value, keyword.arg)
                             for keyword in call.keywords)
            if not imports:
                continue
            indent = source_lines[node.lineno-1].encode('utf-8')[:node.col_offset].decode('utf-8')
            edits.append((node.lineno-1, node.end_lineno,
                          [f'{indent}from {support_module} import '+', '.join(imports),
                           f'{indent}{call.func.id}('+', '.join(arguments)+')']))
        if not edits:
            continue
        if support_path in result:
            raise ValueError(f'generated support path collides with an existing output: {support_path}')
        lines = source_lines[:-1] if source_lines[-1] == '' else source_lines[:]
        for start, end, replacement in reversed(edits):
            lines[start:end] = replacement
        result[path] = '\n'.join(lines)+'\n'
        result[support_path] = '\n'.join([
            '# Generated by svx inheritance-gen.',
            f'# Private execution contracts for {path.as_posix()}.',
            '# Literal data only; registration remains beside the owning declaration.', '', *constants])
        for depth in range(1, len(support_path.parts)):
            initializer = PurePosixPath(*support_path.parts[:depth], '__init__.py')
            if initializer != support_path:
                result.setdefault(initializer, '# Generated by svx inheritance-gen.\n')
    return result


def split_sv_support(sources, *, parse_options=None):
    """Extract record packages without changing their lexical placement.

    The output root must be on the SV include search path. Include fragments
    are not separate compilation units; consumers compile the original roots.
    """
    from .sv_scan import _pyslang, _check_source_diagnostics
    from pyslang import SourceManager
    result = dict(sources)
    for path, source in sources.items():
        if path.suffix != '.sv':
            continue
        tree = _pyslang().SyntaxTree.fromText(source, SourceManager(),
            **({'options': parse_options} if parse_options is not None else {}))
        _check_source_diagnostics(tree, path)
        roots = [tree.root] if hasattr(tree.root, 'header') else getattr(tree.root, 'members', ())
        records = [node for node in roots
                   if str(node.kind) == 'SyntaxKind.PackageDeclaration'
                   and str(node.header.name).strip() == 'svx_call_records_pkg']
        if len(records) > 1:
            raise ValueError(f'multiple call record packages in {path}')
        data = source.encode('utf-8')
        edits = []

        def fragment(nodes, support, role):
            if support in result:
                raise ValueError(f'generated support path collides with an existing output: {support}')
            spans = [(node.sourceRange.start.offset, node.sourceRange.end.offset) for node in nodes]
            result[support] = ('// Generated by svx inheritance-gen.\n'
                               f'// {role}; included by {path.as_posix()}.\n'
                               + '\n\n'.join(data[start:end].decode('utf-8') for start, end in spans)+'\n')
            for index, (start, end) in enumerate(spans):
                replacement = f'`include "{support.as_posix()}"'.encode() if index == 0 else b''
                edits.append((start, end, replacement))

        if records:
            support = PurePosixPath('support') / path.parent / (path.stem+'_call_records.svh')
            fragment(records, support, 'Private call records')
        # Keep executable member logic together. Only shared codec records move.
        for start, end, replacement in sorted(edits, reverse=True):
            data = data[:start]+replacement+data[end:]
        if edits:
            result[path] = data.decode('utf-8')
    return result


def with_sv_support(sources, *, parse_options=None):
    """Assemble editable SV roots, include support and a relocatable -F list."""
    result = split_sv_support(sources, parse_options=parse_options)
    roots = [path for path in sources if path.suffix == '.sv']
    if roots:
        path = PurePosixPath('sources.f')
        if path in result:
            raise ValueError('generated SV filelist path collides with an existing output')
        result[path] = '\n'.join(['// Generated by svx inheritance-gen.', '+incdir+.',
                                 *(f'"{root.as_posix()}"' for root in roots), ''])
    return result
