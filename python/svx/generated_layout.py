"""Keep member logic local, separating only pure contract data and codec records."""
import ast
import re
import json
from collections import deque
from pathlib import PurePosixPath
from .export_timing import measured


@measured('Python contract layout')
def split_python_support(sources, *, contract_literals=None):
    from .generated_names import readable
    from .python_literals import format_literal, LiteralName
    result = dict(sources)
    for path, source in sources.items():
        if path.suffix != '.py' or not source.startswith('# Generated by svx inheritance-gen.'):
            continue
        tree = ast.parse(source)
        # Index lexical owners and candidate statements in one traversal; large
        # contract literals do not need parent entries or global node sorting.
        scopes = {}
        expressions = []
        occupied = set()
        scope_symbols = {}
        def symbols(scope):
            if scope not in scope_symbols:
                imports = {alias.asname or alias.name: alias.name
                           for item in scope.body if isinstance(item, ast.ImportFrom)
                           and item.module == 'svx.inheritance'
                           for alias in item.names if alias.name in {'register_contract', 'register_constructor'}}
                blocked = set()
                arguments = getattr(scope, 'args', None)
                if arguments is not None:
                    blocked.update(arg.arg for arg in
                        (*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs,
                         *((arguments.vararg,) if arguments.vararg else ()),
                         *((arguments.kwarg,) if arguments.kwarg else ())))
                for item in scope.body:
                    if isinstance(item, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
                        blocked.update(child.id for child in ast.walk(item)
                                       if isinstance(child, ast.Name) and isinstance(child.ctx, ast.Store))
                scope_symbols[scope] = imports, blocked
            return scope_symbols[scope]
        def registration(call, scope):
            while scope is not None:
                imports, blocked = symbols(scope)
                if call.func.id in imports:
                    return imports[call.func.id]
                # Do not move a call through a locally shadowed function.
                if call.func.id in blocked:
                    return None
                scope = scopes[scope]
            return None
        pending = deque([(tree, None)])
        scope_types = (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
        while pending:
            node, scope = pending.popleft()
            if isinstance(node, scope_types):
                scopes[node] = scope
                scope = node
            if isinstance(node, ast.Name):
                occupied.add(node.id)
            elif (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
                  and isinstance(node.value.func, ast.Name)):
                call = node.value
                api = registration(call, scope)
                if api is not None:
                    try:
                        values = {id(value): (contract_literals[value.id]
                                  if contract_literals is not None and isinstance(value, ast.Name)
                                  and value.id in contract_literals else ast.literal_eval(value))
                                  for value in (*call.args, *(keyword.value for keyword in call.keywords))}
                    except (ValueError, TypeError):
                        pass
                    else:
                        expressions.append((node, call, api, values))
                        occupied.add(call.func.id)
                        # literal_eval established there are no lexical names
                        # inside the operands; do not traverse them a second time.
                        continue
            pending.extend((child, scope) for child in ast.iter_child_nodes(node))
        edits = []
        constants = []
        support_names = set()
        support_path = PurePosixPath('svx_support') / path
        support_module = '.'.join(support_path.parent.parts if support_path.name == '__init__.py'
                                  else support_path.with_suffix('').parts)
        type_specs = {}
        type_counts = {}
        def type_key(value):
            if (isinstance(value, dict) and 'unified_type_name' in value
                    and 'encoding_descriptor' in value and ('svtypes' in value or 'python' in value)):
                return json.dumps(value, sort_keys=True, separators=(',', ':'))
            return None
        def count_types(value):
            key = type_key(value)
            if key is not None:
                type_specs.setdefault(key, value)
                type_counts[key] = type_counts.get(key, 0) + 1
            elif isinstance(value, dict):
                for item in value.values():
                    count_types(item)
            elif isinstance(value, (tuple, list)):
                for item in value:
                    count_types(item)
        def share_types(value):
            key = type_key(value)
            if key in type_names:
                return LiteralName(type_names[key])
            if isinstance(value, dict):
                return {key: share_types(item) for key, item in value.items()}
            if isinstance(value, (tuple, list)):
                return type(value)(share_types(item) for item in value)
            return value
        # AST columns are UTF-8 byte offsets. Index the file once rather than
        # having get_source_segment split the entire file for every literal.
        data = source.encode('utf-8')
        offsets = [0, *(match.end() for match in re.finditer(rb'\r\n|\r|\n', data))]
        source_lines = re.split(r'\r\n|\r|\n', source)
        def source_segment(node):
            return data[offsets[node.lineno-1]+node.col_offset:
                        offsets[node.end_lineno-1]+node.end_col_offset].decode('utf-8')
        registrations = []
        for node, call, api, values in sorted(expressions, key=lambda item: item[0].lineno):
            if source_lines[node.lineno-1].encode('utf-8')[:node.col_offset].strip():
                continue  # Preserve inline suites and multiple statements.
            if source_lines[node.end_lineno-1].encode('utf-8')[node.end_col_offset:].strip():
                continue
            if any(keyword.arg is None for keyword in call.keywords):
                continue
            registrations.append((node, call, api, values))
            for value in values.values():
                count_types(value)
        type_names = {}
        def type_label(identity):
            kind = identity.get('kind')
            if kind == 'collection':
                args = identity['args']
                return identity['name'] + '_' + type_label(args[0]) + (
                    '_' + str(args[1]) if len(args) > 1 and not isinstance(args[1], dict) else '')
            if kind == 'specialization':
                dimensions = identity.get('args', [[]])[0]
                return identity['base'].get('name', 'value') + '_' + readable(str(dimensions))
            if kind == 'remote_ref':
                return identity['target'].split('://')[-1].partition('#')[0].replace('/', '_') + '_handle'
            return identity.get('qualname') or identity.get('name') or identity.get('symbol') or 'value'
        for key, value in type_specs.items():
            if type_counts[key] < 2:
                continue
            identity = value.get('svtypes') or value.get('python')
            base = '_svx__type_' + readable(type_label(identity))[:48]
            symbol = base
            suffix = 2
            while symbol in support_names:
                symbol = f'{base}_{suffix}'
                suffix += 1
            support_names.add(symbol)
            type_names[key] = symbol
            constants.extend([f'{symbol} = ' + format_literal(value), ''])
        for node, call, api, values in registrations:
            first = values[id(call.args[0])] if call.args else api
            identity = next(iter(first), api) if isinstance(first, dict) else first
            label = readable('/'.join(str(identity).split('/')[-2:]))[:52]
            imports = []
            def operand(value, name):
                if isinstance(value, ast.Constant):
                    return source_segment(value)
                base = label + '_' + name
                symbol = base
                suffix = 2
                while symbol in support_names:
                    symbol = f'{base}_{suffix}'
                    suffix += 1
                support_names.add(symbol)
                alias = '_svx__' + symbol
                while alias in occupied:
                    alias += '_'
                occupied.add(alias)
                imports.append(f'{symbol} as {alias}')
                constants.extend([f'{symbol} = '+format_literal(share_types(values[id(value)])), ''])
                return alias
            names = ('contract',) if api == 'register_contract' else ('class_id', 'parameters')
            arguments = [operand(value, names[index] if index < len(names) else f'argument_{index+1}')
                         for index, value in enumerate(call.args)]
            arguments.extend(keyword.arg+'='+operand(keyword.value, keyword.arg)
                             for keyword in call.keywords)
            if not imports:
                continue
            indent = source_lines[node.lineno-1].encode('utf-8')[:node.col_offset].decode('utf-8')
            edits.append((node.lineno-1, node.end_lineno,
                          [f'{indent}from {support_module} import '+', '.join(imports),
                           f'{indent}{call.func.id}('+', '.join(arguments)+')']))
        if not edits:
            continue
        if support_path in result:
            raise ValueError(f'generated support path collides with an existing output: {support_path}')
        lines = source_lines[:-1] if source_lines[-1] == '' else source_lines[:]
        for start, end, replacement in reversed(edits):
            lines[start:end] = replacement
        result[path] = '\n'.join(lines)+'\n'
        result[support_path] = '\n'.join([
            '# Generated by svx inheritance-gen.',
            f'# Private execution contracts for {path.as_posix()}.',
            '# Literal data only; registration remains beside the owning declaration.', '', *constants])
        for depth in range(1, len(support_path.parts)):
            initializer = PurePosixPath(*support_path.parts[:depth], '__init__.py')
            if initializer != support_path:
                result.setdefault(initializer, '# Generated by svx inheritance-gen.\n')
    return result


def split_sv_support(sources, *, parse_options=None):
    """Extract record packages without changing their lexical placement.

    The output root must be on the SV include search path. Include fragments
    are not separate compilation units; consumers compile the original roots.
    """
    from .sv_scan import _pyslang, _check_source_diagnostics
    from pyslang import SourceManager
    result = dict(sources)
    for path, source in sources.items():
        if path.suffix != '.sv':
            continue
        from .cli import sv_dir
        manager = SourceManager()
        manager.addUserDirectories(str(sv_dir().parent))
        tree = _pyslang().SyntaxTree.fromText(source, manager,
            **({'options': parse_options} if parse_options is not None else {}))
        _check_source_diagnostics(tree, path)
        roots = [tree.root] if hasattr(tree.root, 'header') else getattr(tree.root, 'members', ())
        records = [node for node in roots
                   if str(node.kind) == 'SyntaxKind.PackageDeclaration'
                   and str(node.header.name).strip() == 'svx_call_records_pkg']
        if len(records) > 1:
            raise ValueError(f'multiple call record packages in {path}')
        data = source.encode('utf-8')
        edits = []

        def fragment(nodes, support, role):
            if support in result:
                raise ValueError(f'generated support path collides with an existing output: {support}')
            spans = [(node.sourceRange.start.offset, node.sourceRange.end.offset) for node in nodes]
            result[support] = ('// Generated by svx inheritance-gen.\n'
                               f'// {role}; included by {path.as_posix()}.\n'
                               + '\n\n'.join(data[start:end].decode('utf-8') for start, end in spans)+'\n')
            for index, (start, end) in enumerate(spans):
                replacement = f'`include "{support.as_posix()}"'.encode() if index == 0 else b''
                edits.append((start, end, replacement))

        if records:
            support = PurePosixPath('support') / path.parent / (path.stem+'_call_records.svh')
            fragment(records, support, 'Private call records')
        factory_sections = []
        factory_support = PurePosixPath('support') / path.parent / (path.stem + '_factories.svh')
        for package in roots:
            if str(package.kind) != 'SyntaxKind.PackageDeclaration' or package in records:
                continue
            nodes = []
            for member_index, node in enumerate(package.members):
                start, end = node.sourceRange.start.offset, node.sourceRange.end.offset
                text = data[start:end].decode('utf-8')
                if (re.search(r'\bimplements\s+svx_factory\b', text)
                    or re.match(r'\s*class\s+_svx__\w+_constructor_request\s*;', text)
                    or re.match(r'\s*function\s+void\s+register_\w+_factory\s*\(', text)
                    or re.match(r'[^;\n]+\s+\w+_factory_instance\s*(?:=|;)', text)):
                    nodes.append((member_index, start, end, text))
            if not nodes:
                continue
            groups = []
            for node in nodes:
                if not groups or groups[-1][-1][0] + 1 != node[0]:
                    groups.append([])
                groups[-1].append(node)
            for group_index, group in enumerate(groups):
                selector = '_SVX_FACTORY_' + re.sub(r'\W', '_', str(path) + '_' + str(package.header.name)) + '_' + str(group_index)
                factory_sections.append('`ifdef ' + selector + '\n' + '\n\n'.join(text for _, _, _, text in group) + '\n`endif\n')
                for index, (_, start, end, _) in enumerate(group):
                    replacement = (f'`define {selector}\n`include "{factory_support.as_posix()}"\n`undef {selector}'
                                   if index == 0 else '')
                    edits.append((start, end, replacement.encode()))
        if factory_sections:
            if factory_support in result:
                raise ValueError(f'factory support output collision: {factory_support}')
            result[factory_support] = '// Generated by svx inheritance-gen.\n' + '\n'.join(factory_sections)
        # Keep executable member logic together. Only shared codec records move.
        if edits:
            chunks, cursor = [], 0
            for start, end, replacement in sorted(edits):
                if start < cursor:
                    raise ValueError(f'overlapping generated support edits in {path}')
                chunks.extend((data[cursor:start], replacement))
                cursor = end
            chunks.append(data[cursor:])
            result[path] = b''.join(chunks).decode('utf-8')
    return result


@measured('SV layout, macros and factory support')
def with_sv_support(sources, *, parse_options=None):
    """Assemble editable SV roots, include support and a relocatable -F list."""
    result = split_sv_support(sources, parse_options=parse_options)
    from .field_kernels import compact_field_bindings
    native_aliases = {alias: native for source in sources.values()
                      for native, alias in re.findall(r'\btypedef\s+([\w:]+)\s+(SVX(?:Scoped)?Value_\w+)\s*;', source)}
    for path in sources:
        if path.suffix == '.sv':
            header = PurePosixPath('support') / path.parent / (path.stem + '_fields.svh')
            result[path], definitions = compact_field_bindings(result[path], header.as_posix(), native_aliases)
            if definitions is not None:
                result[header] = definitions
    roots = [path for path in sources if path.suffix == '.sv']
    if roots:
        path = PurePosixPath('sources.f')
        if path in result:
            raise ValueError('generated SV filelist path collides with an existing output')
        result[path] = '\n'.join(['// Generated by svx inheritance-gen.', '+incdir+.',
                                 *(f'"{root.as_posix()}"' for root in roots), ''])
    return result
