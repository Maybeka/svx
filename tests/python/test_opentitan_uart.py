"""Fast checks supplement, never replace, the real upstream simulation campaign."""
import importlib.util
import sys
import subprocess
from pathlib import Path

import pytest
from svx.inheritance import parse_manifest, emit_sv_mirrors, emit_python_mirrors

EXAMPLE = Path(__file__).resolve().parents[2] / "examples/opentitan_uart"


def load(name):
    key = "_svx_uart_example_" + name
    spec = importlib.util.spec_from_file_location(key, EXAMPLE / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[key] = module
    spec.loader.exec_module(module)
    return module


model = load("model")


def frames(values, *, odd=False):
    return [model.Frame(x, 0, 1, (x.bit_count() & 1) ^ odd, True, odd) for x in values]


@pytest.mark.parametrize("odd", [False, True])
def test_independent_streams_and_parity(odd):
    checker = model.UartModel()
    for value in (0, 255, 85, 170):
        checker.sent("TX", value)
        checker.sent("RX", 255 - value)
        checker.read(value, value)
    checker.check({"TX": frames(checker.expected["TX"], odd=odd),
                   "RX": frames(checker.expected["RX"], odd=odd)})


@pytest.mark.parametrize("actual", [[1, 2], [2, 1, 3], [1, 2, 4], [1, 2, 3, 3]])
def test_detects_loss_order_corruption_and_duplication(actual):
    checker = model.UartModel()
    for value in (1, 2, 3):
        checker.sent("TX", value)
    checker.sent("RX", 0)
    with pytest.raises(AssertionError, match="UART_MODEL_STREAM TX"):
        checker.check({"TX": frames(actual), "RX": frames([0])})


def test_bad_frame_parity_and_readback_are_not_silently_accepted():
    checker = model.UartModel()
    checker.sent("TX", 0)
    checker.sent("RX", 0)
    with pytest.raises(AssertionError, match="UART_MODEL_PARITY"):
        checker.check({"TX": [model.Frame(0, 0, 1, 1, True, False)], "RX": frames([0])})
    with pytest.raises(AssertionError, match="UART_MODEL_FRAME"):
        checker.check({"TX": [model.Frame(0, 1, 1, 0, False, False)], "RX": frames([0])})
    with pytest.raises(AssertionError, match="UART_MODEL_READ"):
        checker.read(1, 2)


def test_native_handle_contract_and_selected_generation():
    manifest = parse_manifest(load("generate").manifest_data())
    source = emit_sv_mirrors(manifest)
    python = "\n".join(emit_python_mirrors(manifest).values())
    assert "uart_agent_pkg::uart_item" in source
    assert "class UartSequence" in source
    assert "def observed_item" in python
    assert "def read_rx" in python
    # The upstream source tree is an input, not code copied/generated by SVX.
    assert "class uart_scoreboard" not in source


def test_generation_check_is_read_only(tmp_path):
    command = [sys.executable, str(EXAMPLE / "generate.py"), str(tmp_path)]
    subprocess.run(command, check=True, capture_output=True)
    before = {str(path): (path.read_bytes(), path.stat().st_mtime_ns)
              for path in tmp_path.rglob("*") if path.is_file()}
    subprocess.run([*command, "--check"], check=True, capture_output=True)
    after = {str(path): (path.read_bytes(), path.stat().st_mtime_ns)
             for path in tmp_path.rglob("*") if path.is_file()}
    assert before == after


def test_uart_idle_services_do_not_depend_on_scoreboard_prediction():
    source = (EXAMPLE / "uart_bridge.sv").read_text()
    for name in ("spinwait_txidle", "spinwait_rxidle"):
        body = source.split("virtual task " + name + "();", 1)[1].split("endtask", 1)[0]
        assert "csr_utils_pkg::csr_spinwait" in body
        assert "get_mirrored_value" not in body
