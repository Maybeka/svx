import copy
from pathlib import PurePosixPath

import svtypes

from svx.generated_layout import split_python_support
from svx.inheritance import _type_binding
from svx.declarations import _type_declaration


def test_shared_types_are_data_only_and_registration_does_not_mutate_them(monkeypatch):
    import svx.inheritance as inheritance
    binding = _type_binding(_type_declaration(svtypes.Int, where='test'), 'test', allow_void=False).runtime_spec()
    contract = {'sv://p/Driver#read': {
        'timing': 'function', 'parameters': (('index', 'input', binding),),
        'request': (('index', binding),), 'response': (('result', binding),), 'external_targets': (),
    }}
    source = ('# Generated by svx inheritance-gen.\n'
              'from svx.inheritance import register_contract, register_constructor\n'
              f'register_contract({contract!r})\n'
              f'register_constructor("sv://p/Driver", {(("seed", binding),)!r})\n')
    support = split_python_support({PurePosixPath('driver.py'): source})[PurePosixPath('svx_support/driver.py')]
    namespace = {}
    exec(compile(support, 'support.py', 'exec'), namespace)
    names = [name for name in namespace if name.startswith('_svx__type_')]
    assert names == ['_svx__type_Int']
    shared = namespace[names[0]]
    actual = namespace['p_Driver_read_contract']
    method = actual['sv://p/Driver#read']
    assert method['parameters'][0][2] is shared
    assert method['request'][0][1] is shared and method['response'][0][1] is shared
    parameters = namespace['p_Driver_parameters']
    assert parameters[0][1] is shared
    before = copy.deepcopy(shared)
    monkeypatch.setattr(inheritance, '_method_contracts', {})
    monkeypatch.setattr(inheritance, '_constructor_contracts', {})
    monkeypatch.setattr(inheritance, '_external_handle_targets', set())
    inheritance.register_contract(actual)
    inheritance.register_constructor('sv://p/Driver', parameters)
    first, second = (inheritance._codec_from_spec(shared) for _ in range(2))
    assert first is not second
    first.value = 19
    assert second.value == 0 and shared == before
    assert 'import ' not in support and 'def ' not in support


def test_nominal_types_with_the_same_layout_are_not_merged():
    bindings = [dict(unified_type_name='example.' + name,
                     encoding_descriptor={'encoding_fingerprint': name},
                     svtypes={'kind': 'enum', 'qualname': 'Mode', 'module': name})
                for name in ('first', 'second')]
    value = {'a': (bindings[0], bindings[0]), 'b': (bindings[1], bindings[1])}
    source = ('# Generated by svx inheritance-gen.\nfrom svx.inheritance import register_contract\n'
              f'register_contract({value!r})\n')
    support = split_python_support({PurePosixPath('driver.py'): source})[PurePosixPath('svx_support/driver.py')]
    namespace = {}
    exec(support, namespace)
    assert namespace['_svx__type_Mode'] is not namespace['_svx__type_Mode_2']
    assert namespace['a_contract'] == value


def test_call_record_type_cache_is_command_local_and_values_are_independent():
    from svx.inheritance import call_record_generation, _sv_record_type
    from svx.sv_codegen_mode import type_reference_mode

    binding = _type_binding(_type_declaration(svtypes.Int, where='test'), 'test', allow_void=False)
    fields = (('seed', binding),)
    with call_record_generation():
        first = _sv_record_type('sv://p/Driver', 'request', fields)
        assert _sv_record_type('sv://p/Driver', 'request', fields) is first
        one, two = first(), first()
        one.seed.value = 19
        assert two.seed.value == 0
        with type_reference_mode(True):
            assert _sv_record_type('sv://p/Driver', 'request', fields) is not first
    with call_record_generation():
        assert _sv_record_type('sv://p/Driver', 'request', fields) is not first
