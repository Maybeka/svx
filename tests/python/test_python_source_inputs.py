import io
import json
import sys

import pytest

from svx.cli import main
from svx.errors import SVXInheritanceError
from svx.inheritance import write_generated_sources
from tests.integration.sv_field_mirror_schema import manifest_data


@pytest.mark.parametrize('records', [
    [{'path': 'helper.py', 'sha256': ''}],
    [{'path': 'helper.py', 'sha256': 'z' * 64}],
    [{'path': '/absolute/helper.py', 'sha256': 'a' * 64}],
    [{'path': './helper.py', 'sha256': 'a' * 64}],
    [{'path': 'helper.py', 'sha256': 'a' * 64}, {'path': 'helper.py', 'sha256': 'a' * 64}],
])
def test_invalid_automatic_import_records_preserve_outputs(tmp_path, records):
    source = tmp_path / 'source.py'
    source.write_text('# explicit input\n')
    args = generation_args(tmp_path, source)
    assert main(args, out=io.StringIO()) == 0
    artifact = tmp_path / 'artifacts.json'
    metadata = json.loads(artifact.read_text())
    metadata['generation_inputs']['python_imports'] = records
    artifact.write_text(json.dumps(metadata))
    before = {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
              for path in tmp_path.rglob('*') if path.is_file()}
    for flags in ([], ['--check']):
        with pytest.raises(SVXInheritanceError, match='automatic Python input records'):
            main(args + flags, out=io.StringIO())
        assert before == {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                          for path in tmp_path.rglob('*') if path.is_file()}


@pytest.mark.parametrize('change', ['edit', 'output_collision'])
def test_cached_automatic_generation_import_is_retained_and_protected(tmp_path, monkeypatch, change):
    factory_name = 'audit_cached_factory'
    helper_name = 'audit_cached_helper'
    helper = tmp_path / (helper_name + '.py')
    helper.write_text('# Generated by svx inheritance-gen.\nVALUE = 8\n')
    (tmp_path / (factory_name + '.py')).write_text(
        f'import {helper_name}\nfrom svtypes import Int\ndef make(): return Int()\n')
    data = manifest_data()
    binding = data['classes'][0]['fields'][0]['type']
    binding.pop('svtypes')
    binding['python'] = {'module': factory_name, 'symbol': 'make'}
    manifest = tmp_path / 'manifest.json'
    manifest.write_text(json.dumps(data))
    args = ['inheritance-gen', '--manifest', str(manifest),
            '--python-out', str(tmp_path / 'python'), '--sv-out', str(tmp_path / 'mirrors.sv'),
            '--artifact-manifest', str(tmp_path / 'artifacts.json')]
    monkeypatch.syspath_prepend(str(tmp_path))
    try:
        assert main(args, out=io.StringIO()) == 0
        before = {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                  for path in tmp_path.rglob('*') if path.is_file()}
        assert main(args + ['--check'], out=io.StringIO()) == 0
        assert main(args, out=io.StringIO()) == 0
        assert before == {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                          for path in tmp_path.rglob('*') if path.is_file()}
        if change == 'edit':
            helper.write_text(helper.read_text() + '# changed while cached\n')
            expected = 'source changed while its module is cached'
        else:
            args[args.index('--sv-out') + 1] = str(helper)
            expected = 'input source'
        snapshot = {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                    for path in tmp_path.rglob('*') if path.is_file()}
        with pytest.raises(SVXInheritanceError, match=expected):
            main(args, out=io.StringIO())
        assert snapshot == {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                            for path in tmp_path.rglob('*') if path.is_file()}
    finally:
        sys.modules.pop(factory_name, None)
        sys.modules.pop(helper_name, None)


def generation_args(tmp_path, source):
    manifest = tmp_path / 'manifest.json'
    manifest.write_text(json.dumps(manifest_data()))
    return ['inheritance-gen', '--manifest', str(manifest),
            '--python-source', str(source), '--python-out', str(tmp_path / 'python'),
            '--sv-out', str(tmp_path / 'mirrors.sv'),
            '--artifact-manifest', str(tmp_path / 'artifacts.json')]


@pytest.mark.parametrize('statement', [
    'import gen_cached_types; return gen_cached_types.Codec()',
    'from gen_cached_types import Codec; return Codec()',
    'import importlib; return importlib.import_module("gen_cached_types").Codec()',
])
@pytest.mark.parametrize('changed', [False, True])
def test_first_generation_rejects_unaudited_lazy_cached_dependency(tmp_path, monkeypatch, statement, changed):
    import builtins
    import importlib

    monkeypatch.syspath_prepend(str(tmp_path))
    helper = tmp_path / 'gen_cached_types.py'
    helper.write_text('from svtypes import Int\nCodec = Int\n')
    (tmp_path / 'gen_codec_factory.py').write_text('def make():\n    ' + statement + '\n')
    data = manifest_data()
    binding = data['classes'][0]['fields'][0]['type']
    binding.pop('svtypes')
    binding['python'] = {'module': 'gen_codec_factory', 'symbol': 'make'}
    manifest = tmp_path / 'manifest.json'
    manifest.write_text(json.dumps(data))
    out = tmp_path / 'out'
    args = ['inheritance-gen', '--manifest', str(manifest),
            '--python-out', str(out / 'python'), '--sv-out', str(out / 'mirrors.sv'),
            '--artifact-manifest', str(out / 'artifacts.json')]
    hooks = (builtins.__import__, importlib.import_module)
    try:
        importlib.import_module('gen_cached_types')
        if changed:
            helper.write_text('from svtypes import Bit\nCodec = Bit[16]\n')
        with pytest.raises(SVXInheritanceError, match='dependency is cached without current generation evidence'):
            main(args, out=io.StringIO())
        assert not out.exists()
        assert (builtins.__import__, importlib.import_module) == hooks
        for name in ('gen_cached_types', 'gen_codec_factory'):
            sys.modules.pop(name, None)
        helper.write_text('from svtypes import Int\nCodec = Int\n')
        assert main(args, out=io.StringIO()) == 0
        records = json.loads((out / 'artifacts.json').read_text())['generation_inputs']['python_imports']
        assert any((out / item['path']).resolve() == helper.resolve() for item in records)
        before = {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                  for path in out.rglob('*') if path.is_file()}
        assert main(args + ['--check'], out=io.StringIO()) == 0
        assert main(args, out=io.StringIO()) == 0
        assert before == {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
                          for path in out.rglob('*') if path.is_file()}
    finally:
        for name in ('gen_cached_types', 'gen_codec_factory'):
            sys.modules.pop(name, None)


def test_explicit_framework_source_remains_an_audited_input(tmp_path):
    from pathlib import Path
    import svtypes

    source = Path(svtypes.__file__).resolve()
    args = generation_args(tmp_path, source)
    assert main(args, out=io.StringIO()) == 0
    inputs = json.loads((tmp_path / 'artifacts.json').read_text())['generation_inputs']
    records = inputs['python_sources']
    assert len(records) == 1
    assert (tmp_path / records[0]['path']).resolve() == source
    assert main(args + ['--check'], out=io.StringIO()) == 0


def test_python_source_change_is_stale_even_if_generated_code_matches(tmp_path):
    source = tmp_path / 'source.py'
    source.write_text('raise RuntimeError("input records must not execute this file")\n')
    args = generation_args(tmp_path, source)
    assert main(args, out=io.StringIO()) == 0
    artifacts = tmp_path / 'artifacts.json'
    before = artifacts.read_bytes()
    output = (tmp_path / 'mirrors.sv').read_bytes()
    generated_before = {path: (path.read_bytes(), path.stat().st_mtime_ns)
                        for path in [tmp_path / 'mirrors.sv', *(tmp_path / 'python').rglob('*')]
                        if path.is_file()}
    inputs = json.loads(before)['generation_inputs']
    assert [item['path'] for item in inputs['python_sources']] == ['source.py']
    # Duplicate paths do not change an unordered dependency set.
    assert main(args + ['--python-source', str(source), '--check'], out=io.StringIO()) == 0
    source.write_text(source.read_text() + '# edited without changing the manifest\n')
    with pytest.raises(SystemExit, match='artifacts are stale'):
        main(args + ['--check'], out=io.StringIO())
    assert artifacts.read_bytes() == before
    assert (tmp_path / 'mirrors.sv').read_bytes() == output
    assert main(args, out=io.StringIO()) == 0
    assert (tmp_path / 'mirrors.sv').read_bytes() == output
    assert {path: (path.read_bytes(), path.stat().st_mtime_ns)
            for path in generated_before} == generated_before
    assert main(args + ['--check'], out=io.StringIO()) == 0


@pytest.mark.parametrize('collision', ['direct', 'hardlink', 'obsolete'])
def test_python_input_cannot_be_overwritten_even_with_generated_marker(tmp_path, collision):
    if collision == 'obsolete':
        write_generated_sources({'source.py': '# Generated by svx inheritance-gen. Do not edit.\n'},
                                tmp_path / 'python', '.svx-generated-python.json')
        source = tmp_path / 'python' / 'source.py'
    else:
        source = tmp_path / 'source.py'
        source.write_text('// Generated by svx inheritance-gen. Do not edit.\n')
    args = generation_args(tmp_path, source)
    if collision == 'direct':
        args[args.index('--sv-out') + 1] = str(source)
    elif collision == 'hardlink':
        (tmp_path / 'mirrors.sv').hardlink_to(source)
    snapshot = {path: (path.read_bytes(), path.stat().st_mtime_ns)
                for path in tmp_path.rglob('*') if path.is_file()}
    with pytest.raises(SVXInheritanceError, match='replace or remove input source'):
        main(args, out=io.StringIO())
    assert {path: (path.read_bytes(), path.stat().st_mtime_ns)
            for path in tmp_path.rglob('*') if path.is_file()} == snapshot


def test_missing_python_source_rejected_before_manifest_materialization(tmp_path, monkeypatch):
    args = generation_args(tmp_path, tmp_path / 'missing.py')
    def forbidden_load(path):
        raise AssertionError('invalid input must be rejected before materializing user factories')
    monkeypatch.setattr('svx.cli.load_manifest', forbidden_load)
    with pytest.raises(SVXInheritanceError, match='Python source input is not a file'):
        main(args, out=io.StringIO())
    assert not (tmp_path / 'python').exists()
    assert not (tmp_path / 'mirrors.sv').exists()
    assert not (tmp_path / 'artifacts.json').exists()
