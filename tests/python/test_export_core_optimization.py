import ast
import io
from pathlib import PurePosixPath

from svx.cli import main
from svx.generated_layout import split_python_support


def test_literal_contract_operands_are_not_walked_again(monkeypatch):
    source = ('# Generated by svx inheritance-gen.\n'
              'from svx.inheritance import register_contract\n'
              'register_contract(' + repr({'method': {'payload': list(range(3000))}}) + ')\n')
    original = ast.iter_child_nodes
    visited = []

    def children(node):
        visited.append(node)
        return original(node)

    monkeypatch.setattr(ast, 'iter_child_nodes', children)
    result = split_python_support({PurePosixPath('p.py'): source})
    assert PurePosixPath('svx_support/p.py') in result
    assert not any(isinstance(node, (ast.List, ast.Dict)) for node in visited)


def test_nonliteral_contract_names_still_prevent_alias_collisions():
    source = '''# Generated by svx inheritance-gen.
from svx.inheritance import register_contract
register_contract({'one': {'value': 1}})
other(_svx__one_contract)
register_contract(dynamic_value)
'''
    result = split_python_support({PurePosixPath('p.py'): source})
    assert 'one_contract as _svx__one_contract_' in result[PurePosixPath('p.py')]
    assert 'register_contract(dynamic_value)' in result[PurePosixPath('p.py')]


def test_direct_export_imports_build_configuration_once_per_invocation(tmp_path, monkeypatch):
    import svx.compile_config as config
    source = tmp_path / 'source.sv'
    source.write_text('package p; class Driver; int count; endclass endpackage')
    filelist = tmp_path / 'project.f'
    filelist.write_text(str(source))
    original = config.import_compile_configuration
    calls = []

    def import_config(recipe):
        result = original(recipe)
        calls.append(result)
        return result

    monkeypatch.setattr(config, 'import_compile_configuration', import_config)
    args = ['export', '-f', str(filelist), '--package', 'p', '--out', str(tmp_path / 'generated')]
    assert main(args, out=io.StringIO()) == 0
    assert len(calls) == 1
    assert main([*args, '--check'], out=io.StringIO()) == 0
    assert len(calls) == 2
    # No configuration survives the command: a changed filelist is reread.
    extra = tmp_path / 'extra.sv'
    extra.write_text('package q; class Extra; endclass endpackage')
    filelist.write_text(str(source) + '\n' + str(extra))
    assert main([*args, '--out', str(tmp_path / 'changed')], out=io.StringIO()) == 0
    assert len(calls) == 3
    assert extra.resolve() in calls[-1].sources
