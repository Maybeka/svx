from types import SimpleNamespace
import ast
import keyword
from pathlib import PurePosixPath

import pytest

from svx.generated_names import name_for, with_sv_names


@pytest.mark.parametrize('identity', ['sv://unit/0/Consumer#read', '0', '123:read', '', '$',
                                      '中文', 'class', '0_read', 'value_0_read'])
def test_contract_data_names_are_valid_python_identifiers(identity):
    from svx.generated_layout import split_python_support
    source = ('# Generated by svx inheritance-gen.\n'
              'from svx.inheritance import register_contract\n'
              f'register_contract({{{identity!r}: {{"parameters": ()}}}})\n')
    outputs = split_python_support({PurePosixPath('mirrors.py'): source})
    for path,text in outputs.items():
        tree = ast.parse(text)
        compile(tree, str(path), 'exec')
        for node in ast.walk(tree):
            if isinstance(node, ast.Name):
                assert node.id.isidentifier() and not keyword.iskeyword(node.id)


def test_readable_names_avoid_collisions_and_reset_between_artifacts():
    @with_sv_names
    def generate(manifest):
        return (name_for(('first',), 'ref_Packet'),
                name_for(('second',), 'ref_Packet'),
                name_for(('first',), 'ref_Packet'))
    manifest = SimpleNamespace(classes=())
    assert generate(manifest) == ('_svx__ref_Packet', '_svx__ref_Packet_2', '_svx__ref_Packet')
    assert generate(manifest) == generate(manifest)


def test_generic_native_type_rewrite_does_not_change_adapter_identity():
    from dataclasses import replace
    from svx.inheritance import HandleBinding, _handle_adapter_stem
    for binding in (
        HandleBinding('sv_class', 'sv://unit/0/Item', '$unit::Item'),
        HandleBinding('virtual_interface', 'sv-vif://bus/master', 'virtual bus.master'),
    ):
        assert _handle_adapter_stem(binding) == _handle_adapter_stem(replace(binding, sv_type='SVXNativeHandleType'))


def test_opaque_classes_with_same_leaf_have_distinct_native_helpers(tmp_path):
    from svx.declarations import manifest_from_declarations
    from svx.inheritance import emit_sv_mirrors
    source = tmp_path / 'handles.sv'
    source.write_text('package one; class Packet; endclass endpackage '
                      'package two; class Packet; endclass endpackage '
                      'package drivers; class Driver; function void use_packets(one::Packet a, two::Packet b); '
                      'endfunction endclass endpackage\n', encoding='utf-8')
    manifest = manifest_from_declarations(sv_source_files=[source], sv_class_targets=['drivers::Driver'])
    text = emit_sv_mirrors(manifest)
    assert 'class _svx__ref_Packet extends svx_class_reference#(one::Packet,' in text
    assert 'class _svx__ref_Packet_2 extends svx_class_reference#(two::Packet,' in text
    assert text == emit_sv_mirrors(manifest)


def test_record_name_collisions_keep_artifact_metadata_consistent():
    from copy import deepcopy
    from tests.python.test_m8_inheritance import manifest_data
    from svx.inheritance import parse_manifest, emit_sv_mirrors, emit_python_mirrors, artifact_manifest
    data = manifest_data()
    first = deepcopy(data['classes'][0])
    first['canonical_id'], first['symbol'] = 'sv://a_b/C', 'a_b::C'
    first['methods'][0]['canonical_id'] = 'sv://a_b/C#drive'
    second = deepcopy(first)
    second['canonical_id'], second['symbol'] = 'sv://a/b_C', 'a::b_C'
    second['methods'][0]['canonical_id'] = 'sv://a/b_C#drive'
    data['classes'] = [first, second]
    manifest = parse_manifest(data)
    sv = emit_sv_mirrors(manifest)
    metadata = artifact_manifest(manifest, emit_python_mirrors(manifest), sv)
    names = [item['request_record']['sv_class'] for item in metadata['callables']]
    assert len(set(names)) == 2
    assert all('class '+name.rsplit('::', 1)[-1]+' extends' in sv for name in names)
