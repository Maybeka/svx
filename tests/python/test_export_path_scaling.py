from collections import Counter

import pytest
import svtypes

from svx import sv_scan as scan
from svx.errors import SVXInheritanceError
from svx.inheritance import _emit_sv_deep_field_access


@pytest.mark.parametrize('count', [16, 64, 128])
def test_source_method_checks_index_each_fact_once(monkeypatch, count):
    visits = Counter()

    class Members:
        def __iter__(self):
            for index in range(count):
                visits['members'] += 1
                yield scan.SVInterfaceMemberFact(f'f{index}', 'function', 'int')

    fact = scan.SVClassFact('p::C', None, frozenset(), frozenset(), methods=Members())
    declaration = dict(symbol='p::C', methods=[dict(name=f'f{i}', timing='function') for i in range(count)])
    monkeypatch.setattr(scan, 'scan_sv_sources', lambda *a, **kw: {'p::C': fact})
    monkeypatch.setattr(scan, '_validate_member_types', lambda *a, **kw: None)
    scan.validate_sv_declarations([declaration, declaration], [])
    assert visits['members'] == count


def test_source_method_index_preserves_nearest_declaration_and_virtual_ancestry(monkeypatch):
    parent = scan.SVClassFact('p::A', None, frozenset({'f'}), frozenset({'f'}),
        methods=(scan.SVInterfaceMemberFact('f', 'task'),))
    child = scan.SVClassFact('p::B', 'p::A', frozenset(), frozenset(),
        methods=(scan.SVInterfaceMemberFact('f', 'function', 'int'),))
    monkeypatch.setattr(scan, 'scan_sv_sources', lambda *a, **kw: {'p::A': parent, 'p::B': child})
    monkeypatch.setattr(scan, '_validate_member_types', lambda *a, **kw: None)
    declaration = dict(symbol='p::B', methods=[dict(name='f', virtual=True, timing='function')])
    scan.validate_sv_declarations([declaration], [])
    declaration['methods'][0]['static'] = True
    with pytest.raises(SVXInheritanceError, match=r'p::B.f is static.*not in source'):
        scan.validate_sv_declarations([declaration], [])
    declaration['methods'][0].update(static=False, timing='task')
    with pytest.raises(SVXInheritanceError, match=r'p::B.f timing is task.*function'):
        scan.validate_sv_declarations([declaration], [])
    declaration['methods'][0] = dict(name=['invalid'])
    with pytest.raises(SVXInheritanceError, match='was not found in scanned source lineage'):
        scan.validate_sv_declarations([declaration], [])


@pytest.mark.parametrize('depth', [1, 2, 4, 8])
def test_nested_associative_field_emission_does_not_duplicate_child_subtrees(depth):
    annotation = svtypes.Int
    for _ in range(depth):
        annotation = svtypes.AssocArray[svtypes.Int, annotation]
    text = '\n'.join(_emit_sv_deep_field_access(annotation(), 'this.values', 'sv://p/C.values'))
    assert text.count('unsupported or out-of-range deep field path') == depth + 1
    assert text.count('missing associative field key') == depth
    assert text.count('operation.code == 3 || operation.code == 5') == depth


def test_repeated_private_name_collisions_do_not_restart_suffix_search(monkeypatch):
    import svx.generated_names as names
    visits = Counter()

    class Occupied(set):
        def __contains__(self, value):
            visits['contains'] += 1
            return super().__contains__(value)

    monkeypatch.setattr(names, 'set', Occupied, raising=False)
    with names.sv_name_scope():
        results = [names.name_for(index, 'same') for index in range(512)]
        assert results == ['_svx__same', *(f'_svx__same_{index}' for index in range(2, 513))]
        assert names.name_for(0, 'unused') == results[0]
    assert visits['contains'] <= 3 * len(results)


def test_interleaved_private_names_keep_original_lowest_available_suffixes():
    from svx.generated_names import name_for, readable, sv_name_scope
    occupied = set()
    labels = ['value', 'value_2', 'value', 'value_3', 'value_2', 'value',
              *('long_class_' + 'x' * 100 + str(index) for index in range(80)),
              *('value' for _ in range(80))]
    expected = []
    for label in labels:
        base = '_svx__' + readable(label)[:72].rstrip('_')
        candidate, suffix = base, 2
        while candidate in occupied:
            candidate = f'{base}_{suffix}'
            suffix += 1
        occupied.add(candidate)
        expected.append(candidate)
    with sv_name_scope():
        assert [name_for(index, label) for index, label in enumerate(labels)] == expected


def test_field_template_names_keep_suffix_collisions_and_shape_reuse():
    from svx.field_kernels import compact_field_bindings
    parts = ['// Generated by svx inheritance-gen.\npackage p;']
    for index, (kind, initial) in enumerate([('int', 1), ('int', 2), ('int_2', 3), ('int', 1)]):
        parts.append(f'''    typedef {kind} T{index};
    `SVX_FIELD_ACCESSORS(T{index}, get{index}, set{index}, this.x{index})
    // Core field binding: x{index}
    function void _svx__field_x{index}();
      int value = {initial};
    endfunction''')
    core, support = compact_field_bindings('\n'.join(parts), 'support/mirrors_fields.svh')
    expected = ['_SVX_MIRRORS_FIELD_int', '_SVX_MIRRORS_FIELD_int_2', '_SVX_MIRRORS_FIELD_int_2_2']
    assert [line.split('(')[0].removeprefix('`define ') for line in support.splitlines()
            if line.startswith('`define ')] == expected
    assert core.count('`_SVX_MIRRORS_FIELD_int(') == 2


@pytest.mark.parametrize('header', [b'# Generated by svx inheritance-gen.', b'// Generated by svx inheritance-gen.'])
def test_output_header_preflight_does_not_read_the_complete_artifact(tmp_path, monkeypatch, header):
    from io import BytesIO
    from pathlib import Path
    from svx.inheritance import validate_generated_sources

    target = tmp_path / 'generated.sv'
    target.write_bytes(header + b'\n' + b'x' * (1024 * 1024))
    original = Path.open
    lengths = []

    class Stream(BytesIO):
        def read(self, length=-1):
            lengths.append(length)
            return super().read(length)

    def opened(path, mode='r', *args, **kwargs):
        if path == target and mode == 'rb':
            return Stream(header + b'\n' + b'x' * 100)
        return original(path, mode, *args, **kwargs)

    monkeypatch.setattr(Path, 'open', opened)
    validate_generated_sources({'generated.sv': ''}, tmp_path)
    assert lengths == [len(b'// Generated by svx inheritance-gen.')]


def test_value_discovery_does_not_resolve_unselected_package_typedefs(tmp_path, monkeypatch):
    from svx.declarations import manifest_from_declarations
    source = tmp_path / 'packages.sv'
    source.write_text('package unused;\n' + '\n'.join(
        f'typedef bit [{index}:0] Unused{index};' for index in range(128)) +
        '\nendpackage\npackage dependency; typedef enum bit [1:0] {IDLE, RUN} State; endpackage\n'
        'package chosen; typedef dependency::State StateAlias; endpackage')
    lookups = []
    original = scan._lookup_sv_symbol

    def lookup(compilation, symbol):
        lookups.append(symbol)
        return original(compilation, symbol)

    monkeypatch.setattr(scan, '_lookup_sv_symbol', lookup)
    manifest = manifest_from_declarations(sv_source_files=[source], sv_type_targets=['chosen::StateAlias'])
    assert {value.symbol for value in manifest.value_types} == {'dependency::State', 'chosen::StateAlias'}
    assert not [symbol for symbol in lookups if symbol.startswith('unused::')]
