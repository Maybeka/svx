@pytest.mark.parametrize("length", [2, 3, 4])
def test_python_root_gap_reports_complete_lineage_without_changing_outputs(tmp_path, length):
    from svx.cli import main
    from svx.inheritance import emit_python_mirrors, emit_sv_mirrors, parse_manifest, projection_plan
    from tests.integration.sv_field_mirror_schema import manifest_data

    data = manifest_data()
    manifest = tmp_path / "manifest.json"
    python_dir = tmp_path / "python"
    sv_file = tmp_path / "mirror.sv"
    artifact = tmp_path / "artifacts.json"
    manifest.write_text(json.dumps(data))
    args = ["inheritance-gen", "--manifest", str(manifest), "--python-out", str(python_dir),
            "--sv-out", str(sv_file), "--artifact-manifest", str(artifact)]
    assert main(args, out=StringIO()) == 0
    paths = [*python_dir.rglob("*"), sv_file, artifact]
    before = {path: (path.read_bytes(), path.stat().st_mtime_ns)
              for path in paths if path.is_file()}
    root = {
        "canonical_id": "py://root/B", "language": "python", "symbol": "root.B",
        "methods": [], "fields": data["classes"][0]["fields"],
        "constructor": {"initiator": "python", "parameters": []},
    }
    chain = [root, {
        "canonical_id": "sv://root_pkg/C", "language": "sv", "symbol": "root_pkg::C",
        "methods": [], "constructor": {"initiator": "python", "parameters": []},
    }, {
        "canonical_id": "py://root/D", "language": "python", "symbol": "root.D", "methods": [],
    }, {
        "canonical_id": "sv://root_pkg/E", "language": "sv", "symbol": "root_pkg::E",
        "methods": [], "constructor": {"initiator": "python", "parameters": []},
    }][:length]
    data["classes"] = [{**chain[-1], "base_lineage": chain[:-1]}]
    model = parse_manifest(data)
    plan = projection_plan(model.classes[0])
    assert [cls.canonical_id for cls in plan.lineage] == [cls["canonical_id"] for cls in chain]
    assert len(plan.steps) == length - 1
    manifest.write_text(json.dumps(data))
    for generate in (emit_python_mirrors, emit_sv_mirrors):
        with pytest.raises(SVXInheritanceError, match="Python-root alternating lineage is not implemented") as error:
            generate(model)
        assert " -> ".join(cls["canonical_id"] for cls in chain) in str(error.value)
        assert "an SV ancestor is not required" in str(error.value)
    output = StringIO()
    with pytest.raises(SVXInheritanceError, match="construction/companion bridge"):
        main(args, out=output)
    assert not output.getvalue()
    assert {path: (path.read_bytes(), path.stat().st_mtime_ns) for path in before} == before
    assert {path for path in python_dir.rglob("*") if path.is_file()} == {
        path for path in before if path.is_relative_to(python_dir)
    }


def test_source_body_iteration_preserves_manifest_and_all_generated_timestamps(tmp_path):
    root = Path(__file__).resolve().parents[2]
    source = tmp_path / "source"
    source.mkdir()
    generated = tmp_path / "generated"
    generated.mkdir()
    manifest = generated / "manifest.json"
    python = generated / "python"
    sv = generated / "mirrors.sv"
    artifacts = generated / "artifacts.json"
    environment = dict(os.environ)
    environment["PYTHONPATH"] = os.pathsep.join([
        str(source), str(root / "python"), str(root.parent / "svtypes/python"),
        environment.get("PYTHONPATH", ""),
    ])

    def declaration(module, name, body, parameter="value"):
        return (
            "import svx\nfrom svtypes import Int\n"
            f"@svx.inheritance_class(canonical_id='py://{module}/{name}')\n"
            f"class {name}:\n"
            "    @svx.inheritance_method\n"
            f"    def check(self, {parameter}: Int) -> svx.Function[Int]:\n"
            f"        return {body}\n"
        )

    driver = source / "iteration_driver.py"
    driver.write_text(declaration("iteration_driver", "Driver", "value + 1"))
    (source / "iteration_other.py").write_text(declaration("iteration_other", "Other", "value + 3"))
    discovery = ["inheritance-manifest", "--python-module", "iteration_driver",
                 "--python-module", "iteration_other", "--out", str(manifest)]
    generation = ["inheritance-gen", "--manifest", str(manifest),
                  "--python-out", str(python), "--sv-out", str(sv),
                  "--artifact-manifest", str(artifacts)]

    def command(arguments):
        return subprocess.run([sys.executable, "-m", "svx", *arguments], cwd=root,
                              env=environment, check=True, text=True, capture_output=True)

    def snapshot():
        return {path.relative_to(generated).as_posix(): (path.read_bytes(), path.stat().st_mtime_ns)
                for path in generated.rglob("*") if path.is_file()}

    command(discovery)
    command(generation)
    original = snapshot()
    driver.write_text(declaration("iteration_driver", "Driver", "value + 20"))
    command(discovery)
    command(generation)
    command([*discovery, "--check"])
    command([*generation, "--check"])
    refreshed = snapshot()
    records = {'artifacts.json', 'manifest.json.svx-discovery.json'}
    assert {name: value for name, value in refreshed.items() if name not in records} == {
        name: value for name, value in original.items() if name not in records}, \
        "body-only edits rewrote unchanged contracts or bridges"
    execution = subprocess.run(
        [sys.executable, "-c", "from iteration_driver import Driver; print(Driver().check(1))"],
        cwd=root, env=environment, check=True, text=True, capture_output=True,
    )
    assert execution.stdout.strip() == "21"

    driver.write_text(declaration("iteration_driver", "Driver", "updated_value + 20", "updated_value"))
    command(discovery)
    command(generation)
    revised = snapshot()
    changed = {name for name in original if original[name] != revised[name]}
    assert changed == {"manifest.json", "manifest.json.svx-discovery.json", "mirrors.sv", "artifacts.json", "python/svx_py/iteration_driver.py"}
    assert revised["python/svx_py/iteration_other.py"] == original["python/svx_py/iteration_other.py"]
    command([*generation, "--check"])
