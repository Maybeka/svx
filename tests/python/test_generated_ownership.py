import pytest

from svx import SVXInheritanceError
from svx.inheritance import obsolete_generated_sources, write_generated_sources, write_text_atomic


def test_unchanged_generation_preserves_files_and_inventory(tmp_path):
    marker = ".svx-generated-python.json"
    sources = {Path("generated.py"): "# Generated by svx inheritance-gen.\n"}
    write_generated_sources(sources, tmp_path, marker)
    paths = [tmp_path / "generated.py", tmp_path / marker]
    before = [(path.stat().st_ino, path.stat().st_mtime_ns) for path in paths]
    write_generated_sources(sources, tmp_path, marker)
    assert [(path.stat().st_ino, path.stat().st_mtime_ns) for path in paths] == before


def test_changed_generation_replaces_complete_utf8_content(tmp_path):
    path = tmp_path / "generated.sv"
    write_text_atomic(path, "old\n")
    old_inode = path.stat().st_ino
    write_text_atomic(path, "new\n")
    assert path.read_bytes() == b"new\n"
    assert path.stat().st_ino != old_inode
    assert list(tmp_path.glob("*.tmp")) == []


def test_generation_removes_only_its_owned_obsolete_files(tmp_path):
    marker = ".svx-generated-python.json"
    write_generated_sources({Path("old.py"): "# Generated by svx inheritance-gen.\n"}, tmp_path, marker)
    user_file = tmp_path / "user.py"
    user_file.write_text("user content\n")
    sources = {Path("new.py"): "# Generated by svx inheritance-gen.\n"}
    assert obsolete_generated_sources(tmp_path, sources, marker) == [tmp_path / "old.py"]
    write_generated_sources(sources, tmp_path, marker)
    assert not (tmp_path / "old.py").exists()
    assert user_file.read_text() == "user content\n"
    assert obsolete_generated_sources(tmp_path, sources, marker) == []


def test_inventory_cannot_delete_a_user_file_or_escape_root(tmp_path):
    marker = ".svx-generated-python.json"
    user = tmp_path / "user.py"
    user.write_text("user content\n")
    (tmp_path / marker).write_text('["user.py"]')
    with pytest.raises(SVXInheritanceError, match="refusing to delete"):
        write_generated_sources({}, tmp_path, marker)
    assert user.exists()
    (tmp_path / marker).write_text('["../outside.py"]')
    with pytest.raises(SVXInheritanceError, match="escapes"):
        obsolete_generated_sources(tmp_path, {}, marker)


def test_output_collision_preserves_all_existing_files(tmp_path):
    marker = ".svx-generated-python.json"
    generated = tmp_path / "first.py"
    user = tmp_path / "second.py"
    generated.write_text("# Generated by svx inheritance-gen.\nold\n")
    user.write_text("user implementation\n")
    sources = {
        Path("first.py"): "# Generated by svx inheritance-gen.\nnew\n",
        Path("second.py"): "# Generated by svx inheritance-gen.\nreplacement\n",
    }
    with pytest.raises(SVXInheritanceError, match="non-generated file"):
        write_generated_sources(sources, tmp_path, marker)
    assert generated.read_text().endswith("old\n")
    assert user.read_text() == "user implementation\n"
    assert not (tmp_path / marker).exists()


@pytest.mark.parametrize("state", ["parent_alias", "absolute", "duplicate", "symlink"])
def test_invalid_inventory_is_rejected_before_any_output_changes(tmp_path, state):
    marker = ".svx-generated-python.json"
    current = tmp_path / "current.py"
    old = tmp_path / "old.py"
    current.write_text("# Generated by svx inheritance-gen.\nold current\n")
    old.write_text("# Generated by svx inheritance-gen.\nold obsolete\n")
    (tmp_path / "dir").mkdir()
    entries = {
        "parent_alias": ["dir/../current.py"],
        "absolute": [str(current)],
        "duplicate": ["old.py", "old.py"],
        "symlink": ["link.py"],
    }[state]
    if state == "symlink":
        (tmp_path / "link.py").symlink_to(old)
    (tmp_path / marker).write_text(json.dumps(entries))
    before = {path: (path.read_bytes(), path.stat().st_mtime_ns, path.lstat().st_ino)
              for path in tmp_path.rglob("*") if path.is_file()}
    with pytest.raises(SVXInheritanceError, match="inventory"):
        write_generated_sources({Path("current.py"): "# Generated by svx inheritance-gen.\nnew\n"},
                                tmp_path, marker)
    assert {path: (path.read_bytes(), path.stat().st_mtime_ns, path.lstat().st_ino)
            for path in tmp_path.rglob("*") if path.is_file()} == before


