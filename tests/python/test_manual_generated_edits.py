import hashlib

import pytest

from svx.errors import SVXInheritanceError
from svx.generated_ownership import protect_manual_edits


def test_regeneration_protects_modified_core_but_not_unrelated_files(tmp_path):
    core = tmp_path/'mirror.py'
    core.write_text('# Generated by svx inheritance-gen.\nVALUE=1\n')
    previous = {'artifacts': [{'path': core.name, 'sha256': hashlib.sha256(core.read_bytes()).hexdigest()}]}
    artifact = tmp_path/'artifacts.json'
    protect_manual_edits(previous, artifact, [core])
    core.write_text('# Generated by svx inheritance-gen.\nVALUE=2\n')
    with pytest.raises(SVXInheritanceError, match='recorded snapshot'):
        protect_manual_edits(previous, artifact, [core])
    assert 'VALUE=2' in core.read_text()
    protect_manual_edits(previous, artifact, [core], overwrite=True)
    protect_manual_edits(previous, artifact, [tmp_path/'other.py'])


def test_explicit_overwrite_flag_is_supported_by_both_generation_commands():
    from svx.cli import build_parser
    parser = build_parser()
    for arguments in (['export', '--out', 'generated'],
                      ['inheritance-gen', '--manifest', 'manifest.json']):
        assert parser.parse_args([*arguments, '--overwrite-generated']).overwrite_generated


def test_cli_does_not_overwrite_a_core_patch_without_consent(tmp_path):
    import io
    import json
    from svx.cli import main
    from tests.integration.sv_field_mirror_schema import manifest_data
    manifest = tmp_path/'manifest.json'
    manifest.write_text(json.dumps(manifest_data()), encoding='utf-8')
    python = tmp_path/'python'
    artifact = tmp_path/'artifacts.json'
    args = ['inheritance-gen', '--manifest', str(manifest), '--python-out', str(python),
            '--sv-out', str(tmp_path/'mirrors.sv'), '--artifact-manifest', str(artifact)]
    assert main(args, out=io.StringIO()) == 0
    core = next(path for path in (python/'svx_mirror').rglob('*.py') if path.name != '__init__.py')
    patch = core.read_text()+'\n# local repair\n'
    core.write_text(patch, encoding='utf-8')
    metadata = artifact.read_bytes()
    with pytest.raises(SVXInheritanceError, match='recorded snapshot'):
        main(args, out=io.StringIO())
    assert core.read_text() == patch and artifact.read_bytes() == metadata
    assert main([*args, '--overwrite-generated'], out=io.StringIO()) == 0
    assert '# local repair' not in core.read_text()


def test_direct_writer_protects_core_without_artifact_manifest(tmp_path):
    from pathlib import PurePosixPath
    from svx.inheritance import write_generated_sources
    path = PurePosixPath('mirror.py')
    old = '# Generated by svx inheritance-gen.\nVALUE=1\n'
    new = '# Generated by svx inheritance-gen.\nVALUE=3\n'
    write_generated_sources({path: old}, tmp_path, '.inventory.json')
    (tmp_path/path).write_text(old+'# local patch\n')
    with pytest.raises(SVXInheritanceError, match='recorded snapshot'):
        write_generated_sources({path: new}, tmp_path, '.inventory.json')
    assert '# local patch' in (tmp_path/path).read_text()
    write_generated_sources({path: new}, tmp_path, '.inventory.json', overwrite=True)
    assert (tmp_path/path).read_text() == new


def test_single_sv_output_preserves_manual_patch_without_artifact_manifest(tmp_path):
    import io
    import json
    from svx.cli import main
    from tests.integration.sv_field_mirror_schema import manifest_data
    manifest = tmp_path/'manifest.json'
    manifest.write_text(json.dumps(manifest_data()), encoding='utf-8')
    sv = tmp_path/'mirrors.sv'
    args = ['inheritance-gen', '--manifest', str(manifest),
            '--python-out', str(tmp_path/'python'), '--sv-out', str(sv)]
    assert main(args, out=io.StringIO()) == 0
    original = sv.read_text(encoding='utf-8')
    sv.write_text(original+'\n// local repair\n', encoding='utf-8')
    with pytest.raises(SVXInheritanceError, match='recorded snapshot'):
        main(args, out=io.StringIO())
    assert sv.read_text(encoding='utf-8').endswith('// local repair\n')
    assert main([*args, '--overwrite-generated'], out=io.StringIO()) == 0
    assert sv.read_text(encoding='utf-8') == original


def test_missing_baseline_does_not_silently_replace_or_retire_existing_files(tmp_path):
    from svx.generated_ownership import protect_baseline
    core = tmp_path/'mirror.sv'
    core.write_text('// local repair\n', encoding='utf-8')
    with pytest.raises(SVXInheritanceError, match='without a recorded snapshot'):
        protect_baseline(tmp_path, 'inventory.json', {'mirror.sv': '// generated\n'}, ())
    with pytest.raises(SVXInheritanceError, match='cannot retire'):
        protect_baseline(tmp_path, 'inventory.json', {}, (core,))
    protect_baseline(tmp_path, 'inventory.json', {'mirror.sv': '// local repair\n'}, ())
    protect_baseline(tmp_path, 'inventory.json', {'mirror.sv': '// generated\n'}, (), overwrite=True)
