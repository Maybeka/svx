"""Exercise inventory failure and recovery through the public generation CLI."""

import json
import tempfile
from io import StringIO
from pathlib import Path

from svx import SVXInheritanceError
from svx.cli import main
from tests.integration.sv_field_mirror_schema import manifest_data


def verify_inventory_safety(root: Path, *, stage: bool, state: str) -> None:
    manifest = root / "manifest.json"
    python = root / "python"
    sv = root / ("stages" if stage else "mirrors.sv")
    artifact = root / "artifacts.json"
    data = manifest_data()
    manifest.write_text(json.dumps(data))
    arguments = ["inheritance-gen", "--manifest", str(manifest),
                 "--python-out", str(python),
                 "--sv-stage-dir" if stage else "--sv-out", str(sv),
                 "--artifact-manifest", str(artifact)]
    assert main(arguments, out=StringIO()) == 0
    output = sv if stage else python
    inventory = output / (".svx-generated-sv.json" if stage else ".svx-generated-python.json")
    original = inventory.read_text()
    victim = json.loads(original)[0]
    (output / "alias").mkdir()
    if state == "parent_alias":
        entries = ["alias/../" + victim]
    elif state == "absolute":
        entries = [str((output / victim).resolve())]
    else:
        retired = output / "retired.py"
        retired.write_text("# Generated by svx inheritance-gen.\n")
        if state == "duplicate":
            entries = ["retired.py", "retired.py"]
        elif state == "symlink":
            (output / "link.py").symlink_to(retired)
            entries = ["link.py"]
        else:
            raise ValueError(state)
    inventory.write_text(json.dumps(entries))
    data["classes"][0]["methods"][0]["parameters"] = [
        {"name": "new_input", "type": data["classes"][0]["fields"][0]["type"]}
    ]
    manifest.write_text(json.dumps(data))

    def snapshot():
        return {path: (path.read_bytes(), path.stat().st_mtime_ns, path.lstat().st_ino)
                for path in root.rglob("*") if path.is_file()}

    before = snapshot()
    messages = StringIO()
    try:
        main(arguments, out=messages)
    except SVXInheritanceError as error:
        assert "inventory" in str(error), str(error)
    else:
        raise AssertionError("invalid inventory was accepted")
    assert not messages.getvalue()
    assert snapshot() == before
    inventory.write_text(original)
    assert main(arguments, out=StringIO()) == 0
    assert main([*arguments, "--check"], out=StringIO()) == 0
    refreshed = snapshot()
    assert main(arguments, out=StringIO()) == 0
    assert snapshot() == refreshed


if __name__ == "__main__":
    for stage in (False, True):
        for state in ("parent_alias", "absolute", "duplicate", "symlink"):
            with tempfile.TemporaryDirectory(prefix="svx-inventory-") as directory:
                verify_inventory_safety(Path(directory), stage=stage, state=state)
            print(f"INVENTORY_CASE_PASS stage={stage} state={state}")
    print("GENERATED_INVENTORY_SAFETY_PASS")
