"""Exercise the discovery evidence consumer without a test-runner dependency."""

import hashlib
import io
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from svx.cli import main
from svx.discovery_provenance import discovery_contract_digest
from svx.errors import SVXInheritanceError
from svx.inheritance import load_manifest
from tests.integration.sv_field_mirror_schema import manifest_data


def setup_record(root):
    source = root / 'declaration_types.py'
    source.write_text('# Generated by svx inheritance-gen.\nScalar = 8\n')
    data = manifest_data()
    data['discovery_provenance'] = {'schema_version': '1.0.0', 'path': 'discovery.json'}
    manifest = root / 'manifest.json'
    manifest.write_text(json.dumps(data))
    record = {'schema_version': '1.0.0', 'contract_sha256': discovery_contract_digest(data),
              # This metadata-only consumer fixture does not import a Python
              # declaration entry; real source selection has separate CLI probes.
              'configuration': {'python_sources': [source.name]},
              'sources': [{'path': source.name, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()}]}
    evidence = root / 'discovery.json'
    evidence.write_text(json.dumps(record))
    return manifest, source, evidence, data, record


def snapshot(root):
    return {path: (path.read_bytes(), path.stat().st_mtime_ns, path.stat().st_ino)
            for path in root.rglob('*') if path.is_file()}


def run():
    import svx.inheritance

    for damage in ('source_edit', 'missing_source', 'missing_record', 'contract_edit',
                   'bad_digest', 'duplicate_source', 'absolute_source', 'alias_source', 'null_marker',
                   'mode_list', 'mode_mapping'):
        with TemporaryDirectory() as directory:
            root = Path(directory)
            manifest, source, evidence, data, record = setup_record(root)
            args = ['inheritance-gen', '--manifest', str(manifest),
                    '--python-out', str(root / 'generated' / 'python'),
                    '--sv-out', str(root / 'generated' / 'mirrors.sv'),
                    '--artifact-manifest', str(root / 'generated' / 'artifacts.json')]
            assert main(args, out=io.StringIO()) == 0
            assert main(args + ['--check'], out=io.StringIO()) == 0
            if damage == 'source_edit':
                source.write_text('Scalar = 16\n')
            elif damage == 'missing_source':
                source.unlink()
            elif damage == 'missing_record':
                evidence.unlink()
            elif damage == 'contract_edit':
                data['classes'][0]['canonical_id'] += 'Changed'
                manifest.write_text(json.dumps(data))
            elif damage == 'null_marker':
                data['discovery_provenance'] = None
                manifest.write_text(json.dumps(data))
            else:
                if damage == 'bad_digest':
                    record['sources'][0]['sha256'] = 'invalid'
                elif damage == 'duplicate_source':
                    record['sources'].append(dict(record['sources'][0]))
                elif damage == 'absolute_source':
                    record['sources'][0]['path'] = str(source)
                elif damage == 'alias_source':
                    (root / 'alias.py').symlink_to(source)
                    record['sources'].append({**record['sources'][0], 'path': 'alias.py'})
                else:
                    record['configuration']['source_mode'] = [] if damage == 'mode_list' else {}
                evidence.write_text(json.dumps(record))
            before = snapshot(root)
            original = svx.inheritance._parse_class

            def forbidden(*args, **kwargs):
                raise AssertionError('stale provenance reached class parsing')

            svx.inheritance._parse_class = forbidden
            try:
                calls = [lambda: load_manifest(manifest)]
                calls.extend(lambda flags=flags: main(args + flags, out=io.StringIO())
                             for flags in ([], ['--check']))
                for call in calls:
                    try:
                        call()
                    except SVXInheritanceError as error:
                        assert 'discovery' in str(error), error
                    else:
                        raise AssertionError('stale discovery evidence was accepted')
                    assert snapshot(root) == before
            finally:
                svx.inheritance._parse_class = original
        print('DISCOVERY_PROVENANCE_REJECTION_PASS ' + damage, flush=True)
    print('DISCOVERY_PROVENANCE_CONTRACT_PASS', flush=True)


if __name__ == '__main__':
    run()
