#!/usr/bin/env python3
"""Generate the narrow SV proxy surface used by the incubated UVMX U0."""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path
import re
import sys
from typing import Iterable


_USER_BASE = re.compile(
    r"\bclass\s+([A-Za-z_][A-Za-z0-9_$]*)\s+extends\s+([A-Za-z_][A-Za-z0-9_$:]*)"
)


def _require_uvmx():
    try:
        from uvmx.declarations import UvmTestDeclaration, declared_tests
    except ImportError as error:  # pragma: no cover - command environment error
        raise SystemExit(
            "cannot import uvmx; add incubator/uvmx/python and SVX python to PYTHONPATH"
        ) from error
    return UvmTestDeclaration, declared_tests


def _validate_user_bases(declarations: Iterable[object], sources: tuple[Path, ...]) -> None:
    declared = tuple(item for item in declarations if item.sv_base != "uvm_pkg::uvm_test")
    if not declared:
        return
    if not sources:
        names = ", ".join(item.sv_base for item in declared)
        raise ValueError(
            "non-default sv_base requires at least one --sv-base-source for U0 validation: " + names
        )
    parsed: dict[str, str] = {}
    for path in sources:
        text = path.read_text(encoding="utf-8")
        for name, base in _USER_BASE.findall(text):
            parsed[name] = base
    for declaration in declared:
        class_name = declaration.sv_base.rsplit("::", 1)[-1]
        base = parsed.get(class_name)
        if base is None:
            raise ValueError(
                f"cannot validate sv_base {declaration.sv_base!r}: class {class_name!r} "
                "was not found in --sv-base-source"
            )
        if base.rsplit("::", 1)[-1] != "uvm_test":
            raise ValueError(
                f"U0 sv_base {declaration.sv_base!r} must directly extend uvm_test; "
                f"found extends {base!r}"
            )


def _sv_quote(value: str) -> str:
    return json.dumps(value)


def _emit_proxy(declaration: object) -> list[str]:
    method_prefix = declaration.canonical_id
    class_name = declaration.factory_name
    lines = [
        "",
        f"  // Generated UVMX U0 proxy for {declaration.canonical_id}.",
        f"  class {class_name} extends {declaration.sv_base} implements svx_dispatchable;",
        f"    `uvm_component_utils({class_name})",
        "    longint unsigned __uvmx_object_id;",
        "",
        "    function new(string name = \"\", uvm_component parent = null);",
        "      super.new(name, parent);",
        f"      __uvmx_object_id = uvmx_bridge_bind({_sv_quote(declaration.canonical_id)}, this);",
        "    endfunction",
        "",
        "    virtual task svx_invoke(",
        "      string method_id, input chandle request, output bit ok,",
        "      output chandle response, output string error",
        "    );",
        "      ok = 0;",
        "      response = null;",
        "      error = {\"UVMX U0 proxy is Python callback-only: \", method_id};",
        "    endtask",
    ]
    for phase in declaration.function_phases:
        lines.extend(
            [
                "",
                f"    virtual function void {phase}(uvm_phase phase);",
                f"      super.{phase}(phase);",
                f"      uvmx_bridge_call_function(__uvmx_object_id, {_sv_quote(method_prefix + '#' + phase)});",
                "    endfunction",
            ]
        )
    for phase in declaration.task_phases:
        lines.extend(
            [
                "",
                f"    virtual task {phase}(uvm_phase phase);",
                f"      super.{phase}(phase);",
                "      phase.raise_objection(this, \"UVMX mapped Python test active\");",
                f"      uvmx_bridge_call_task(__uvmx_object_id, {_sv_quote(method_prefix + '#' + phase)});",
                "      phase.drop_objection(this, \"UVMX mapped Python test completed\");",
                "    endtask",
            ]
        )
    lines.extend(["  endclass", ""])
    return lines


def render_sv(declarations: Iterable[object], package_name: str) -> str:
    lines = [
        "// Generated by incubator/uvmx/tools/uvmx_gen.py. Do not edit.",
        f"package {package_name};",
        "  import uvm_pkg::*;",
        "  import svx_pkg::*;",
        "  import uvmx_pkg::*;",
        "  `include \"uvm_macros.svh\"",
    ]
    for declaration in declarations:
        lines.extend(_emit_proxy(declaration))
    lines.extend([f"endpackage : {package_name}", ""])
    return "\n".join(lines)


def artifact_manifest(declarations: Iterable[object], package_name: str) -> dict[str, object]:
    return {
        "schema_uri": "https://svx.dev/schema/uvmx-bootstrap-artifacts/v1",
        "uvmx_stage": "U0",
        "svx_contract": "cross_language_inheritance",
        "svtypes_contract": "1.x",
        "package": package_name,
        "tests": [
            {
                "canonical_id": item.canonical_id,
                "factory_name": item.factory_name,
                "sv_base": item.sv_base,
                "python": f"{item.module}.{item.qualname}",
                "function_phases": list(item.function_phases),
                "task_phases": list(item.task_phases),
            }
            for item in declarations
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--module", required=True, help="Python module containing @uvm_test declarations")
    parser.add_argument("--sv-out", required=True, type=Path)
    parser.add_argument("--artifact-manifest", required=True, type=Path)
    parser.add_argument("--package", default="uvmx_generated_pkg")
    parser.add_argument("--sv-base-source", action="append", default=[], type=Path)
    options = parser.parse_args(argv)

    _, declared_tests = _require_uvmx()
    importlib.import_module(options.module)
    declarations = declared_tests(options.module)
    if not declarations:
        raise SystemExit(f"{options.module!r} contains no @uvm_test declarations")
    _validate_user_bases(declarations, tuple(options.sv_base_source))

    options.sv_out.parent.mkdir(parents=True, exist_ok=True)
    options.sv_out.write_text(render_sv(declarations, options.package), encoding="utf-8")
    options.artifact_manifest.parent.mkdir(parents=True, exist_ok=True)
    options.artifact_manifest.write_text(
        json.dumps(artifact_manifest(declarations, options.package), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
