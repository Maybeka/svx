#!/usr/bin/env python3
"""Compile reusable SV base bridges, never per-Python-test SV classes."""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path
import re
import sys
from typing import Iterable


_USER_BASE = re.compile(
    r"\bclass\s+([A-Za-z_][A-Za-z0-9_$]*)\s+extends\s+([A-Za-z_][A-Za-z0-9_$:]*)"
)


def _require_uvmx():
    try:
        from uvmx.declarations import UvmTestDeclaration, declared_tests
    except ImportError as error:  # pragma: no cover - command environment error
        raise SystemExit(
            "cannot import uvmx; add incubator/uvmx/python and SVX python to PYTHONPATH"
        ) from error
    return UvmTestDeclaration, declared_tests


def _validate_user_bases(declarations: Iterable[object], sources: tuple[Path, ...]) -> None:
    declared = tuple(item for item in declarations if item.sv_base != "uvm_pkg::uvm_test")
    if not declared:
        return
    if not sources:
        names = ", ".join(item.sv_base for item in declared)
        raise ValueError(
            "non-default sv_base requires at least one --sv-base-source for U0 validation: " + names
        )
    parsed: dict[str, str] = {}
    for path in sources:
        text = path.read_text(encoding="utf-8")
        for name, base in _USER_BASE.findall(text):
            parsed[name] = base
    for declaration in declared:
        class_name = declaration.sv_base.rsplit("::", 1)[-1]
        base = parsed.get(class_name)
        if base is None:
            raise ValueError(
                f"cannot validate sv_base {declaration.sv_base!r}: class {class_name!r} "
                "was not found in --sv-base-source"
            )
        if base.rsplit("::", 1)[-1] != "uvm_test":
            raise ValueError(
                f"U0 sv_base {declaration.sv_base!r} must directly extend uvm_test; "
                f"found extends {base!r}"
            )


def render_sv(declarations: Iterable[object], package_name: str) -> str:
    declarations = tuple(declarations)
    lines = [
        "// Generated by incubator/uvmx/tools/uvmx_gen.py. Do not edit.",
        f"package {package_name};",
        "  import uvm_pkg::*;",
        "  import svx_pkg::*;",
        "  import uvmx_pkg::*;",
        "  `include \"uvm_macros.svh\"",
    ]
    bases = sorted({item.sv_base for item in declarations} - {'uvm_pkg::uvm_test'})
    for index, base in enumerate(bases):
        lines.extend([
            f'  function automatic bit __uvmx_register_base_{index}();',
            f'    uvmx_typed_base_factory#({base}) factory = new();',
            f'    uvmx_base_registry::add({json.dumps(base)}, factory);',
            '    return 1;', '  endfunction',
            f'  bit __uvmx_base_{index} = __uvmx_register_base_{index}();',
        ])
    lines.extend([f"endpackage : {package_name}", ""])
    return "\n".join(lines)


def artifact_manifest(declarations: Iterable[object], package_name: str) -> dict[str, object]:
    return {
        "schema_uri": "https://svx.dev/schema/uvmx-bootstrap-artifacts/v1",
        "uvmx_stage": "U0",
        "svx_contract": "svx.callbacks.v1",
        "svtypes_contract": "1.x",
        "package": package_name,
        "sv_bases": sorted({item.sv_base for item in declarations}),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--module", required=True, help="Python module containing @uvm_test declarations")
    parser.add_argument("--sv-out", required=True, type=Path)
    parser.add_argument("--artifact-manifest", required=True, type=Path)
    parser.add_argument("--package", default="uvmx_generated_pkg")
    parser.add_argument("--sv-base-source", action="append", default=[], type=Path)
    options = parser.parse_args(argv)

    _, declared_tests = _require_uvmx()
    importlib.import_module(options.module)
    declarations = declared_tests()
    if not declarations:
        raise SystemExit(f"{options.module!r} contains no @uvm_test declarations")
    _validate_user_bases(declarations, tuple(options.sv_base_source))

    options.sv_out.parent.mkdir(parents=True, exist_ok=True)
    options.sv_out.write_text(render_sv(declarations, options.package), encoding="utf-8")
    options.artifact_manifest.parent.mkdir(parents=True, exist_ok=True)
    options.artifact_manifest.write_text(
        json.dumps(artifact_manifest(declarations, options.package), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
